"""The frontend (`marco-m-netflix`, another repository) renders the `cinema_sql_calls` step from the payload the backend really produces.

The frontend has no test runner: this runs its pure `render.js` in Node 22 on the example of the contract (generated by the real serializer and kept in sync by
`tests/web_api/test_web_api_doc.py`). Skipped when the frontend checkout or Node 22 is not there.
"""
from __future__ import annotations

import json
import re
import shutil
import subprocess
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
FRONTEND = ROOT.parent / "marco-m-netflix" / "src" / "features" / "chat" / "messages" / "render.js"
NODE = Path.home() / ".nvm" / "versions" / "node"


def node22() -> str | None:
    found = sorted(NODE.glob("v22.*/bin/node")) if NODE.exists() else []
    if found:
        return str(found[-1])
    path = shutil.which("node")
    if path:
        version = subprocess.run([path, "-v"], capture_output=True, text=True).stdout.strip()
        return path if version.startswith("v22") else None
    return None


pytestmark = pytest.mark.skipif(not FRONTEND.exists() or node22() is None, reason="frontend checkout or Node 22 not available")


def contract_step() -> dict:
    text = (ROOT / "web_api" / "contracts" / "chat_stream.md").read_text(encoding="utf-8")
    return json.loads(re.search(r"```json step=cinema_sql_calls\n(.+?)\n```", text, re.S).group(1))


def render(step: dict) -> dict:
    script = ("import { readFileSync } from 'node:fs';"
              f"import {{ stepToEntry }} from {json.dumps(FRONTEND.as_uri())};"
              "console.log(JSON.stringify(stepToEntry(JSON.parse(readFileSync(0, 'utf8')))));")
    out = subprocess.run([node22(), "--input-type=module", "-e", script], input=json.dumps(step), capture_output=True, text=True, timeout=60)
    assert out.returncode == 0, out.stderr
    return json.loads(out.stdout)


def test_the_step_shows_the_provenance_of_the_data_the_public_pages_and_the_limits():
    entry = render(contract_step())
    assert entry["stepKind"] == "cinema_sql_calls" and entry["title"] == "ARCHIVIO LOCALE"
    assert entry["attributions"] == [contract_step()["source"]] and "Wikipedia" in entry["attributions"][0] and "Wikidata" in entry["attributions"][0]
    urls = [link["url"] for link in entry["links"]]
    assert any(u.startswith("https://it.wikipedia.org/wiki/") for u in urls) and any(u.startswith("https://www.wikidata.org/wiki/") for u in urls)
    assert any("creativecommons.org" in u for u in urls)
    assert any(line.startswith("Limiti dei dati") for line in entry["lines"]) and any("Mostrati" in line for line in entry["lines"])
    assert any("Nessuna richiesta di rete" in line for line in entry["lines"])


def test_nothing_internal_reaches_the_screen_and_unsafe_links_are_dropped():
    step = contract_step()
    step["subject"]["links"].append({"label": "x", "url": "javascript:alert(1)"})
    text = json.dumps(render(step)).lower()
    for internal in ("select ", " v_", "work_id", "person_id", "javascript:"):
        assert internal not in text
