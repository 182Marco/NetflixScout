"""Generates the schema documentation and the SQL tool's approved-view policy from the REAL SQLite schema.

    python -m cinema_db.harness.schema.generate            # builds a schema-only database in a temp folder, writes the files
    python -m cinema_db.harness.schema.generate --db FILE  # same, from an existing database (row counts and sources shown)
    python -m cinema_db.harness.schema.generate --check    # writes nothing; exit 1 if a generated file is stale

Outputs: docs/cinema_db/schema.html, docs/cinema_db/schema.mmd, tool/cinema_db/approved_views.py.
Fails if any table, view or column has no description (cinema_db/schema_notes.py) or a description names something missing.
"""
from __future__ import annotations

import argparse
import sqlite3
import sys
import tempfile
from pathlib import Path
from typing import Any

from cinema_db import schema_notes as N
from cinema_db.harness.schema import render
from cinema_db.harness.schema.introspect import NotesIncomplete, check_notes, introspect
from cinema_db.schema import create_database

ROOT = Path(__file__).resolve().parents[3]
HTML = ROOT / "docs/cinema_db/schema.html"
MERMAID = ROOT / "docs/cinema_db/schema.mmd"
POLICY = ROOT / "tool/cinema_db/approved_views.py"


def policy_module(info: dict[str, Any]) -> str:
    s = info["structure"]
    lines = [
        '"""Approved views of the cinema database: what `cinema_sql` may read. GENERATED by',
        "cinema_db/harness/schema/generate.py from the real SQLite schema (do not edit; a test fails if it is stale).",
        "",
        "`connection.verify_policy` checks this policy against the database file every time a connection opens.",
        '"""',
        "from __future__ import annotations",
        "",
        "from .policy import Policy, ViewSpec",
        "",
        f"STRUCTURE_DIGEST = {info['structure_digest']!r}",
        "",
        "VIEWS = (",
    ]
    for v in s["views"]:
        lines.append("    ViewSpec(")
        lines.append(f"        {v['name']!r},")
        lines.append("        (")
        for c in v["columns"]:
            lines.append(f"            ({c['name']!r}, {c['type'].upper()!r}),")
        lines.append("        ),")
        lines.append(f"        {v['doc']!r},")
        lines.append("    ),")
    lines.append(")")
    base: dict[str, set[str]] = {}
    for v in s["views"]:
        for key in v["base_columns"]:
            t, c = key.split(".")
            base.setdefault(t, set()).add(c)
    lines += ["", "BASE_COLUMNS = {"]
    for t in sorted(base):
        lines.append(f"    {t!r}: frozenset({{{', '.join(repr(c) for c in sorted(base[t]))}}}),")
    engine_tables = sorted({n for vt in s["virtual_tables"] for n in [vt["name"], *vt["shadow_tables"]]})
    lines += [
        "}", "",
        "LARGE_TABLES = frozenset({" + ", ".join(repr(t) for t in sorted(N.LARGE_TABLES)) + "})",
        "# SQLite's own needs when a view reads the FTS5 virtual table (allowed to the authorizer only; never in model SQL).",
        "ENGINE_TABLES = frozenset({" + ", ".join(repr(t) for t in engine_tables) + "})",
        "ENGINE_COLUMNS = frozenset({" + ", ".join(repr(c) for c in sorted(f"{vt['content_table']}.{c}" for vt in s["virtual_tables"] if vt["content_table"] for c in vt["content_columns"])) + "})",
        "ENGINE_FUNCTIONS = frozenset({" + ", ".join(repr(f) for f in sorted(s["engine"]["functions"])) + "})",
        "ENGINE_PRAGMAS = frozenset({" + ", ".join(repr(f) for f in sorted(s["engine"]["pragmas"])) + "})",
        "",
        "POLICY = Policy(",
        "    views=VIEWS, base_columns=BASE_COLUMNS, large_tables=LARGE_TABLES,",
        "    engine_tables=ENGINE_TABLES, engine_columns=ENGINE_COLUMNS, engine_functions=ENGINE_FUNCTIONS, engine_pragmas=ENGINE_PRAGMAS,",
        ")",
        "",
    ]
    return "\n".join(lines)


def generate(db: Path | None) -> dict[str, str]:
    with tempfile.TemporaryDirectory() as tmp:
        path = db or create_database(Path(tmp) / "schema_only.sqlite3")
        conn = sqlite3.connect(f"file:{path}?mode=ro", uri=True)
        try:
            info = introspect(conn)
        finally:
            conn.close()
    problems = check_notes(info)
    if problems:
        raise NotesIncomplete("\n".join(problems))
    return {str(HTML): render.html(info), str(MERMAID): render.mermaid(info), str(POLICY): policy_module(info)}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--db", type=Path)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    try:
        outputs = generate(args.db)
    except NotesIncomplete as exc:
        print("Schema notes are incomplete or stale:\n" + str(exc), file=sys.stderr)
        return 2
    stale = [p for p, text in outputs.items() if not Path(p).is_file() or Path(p).read_text(encoding="utf-8") != text]
    if args.check:
        for p in stale:
            print(f"STALE: {p}", file=sys.stderr)
        return 1 if stale else 0
    for p, text in outputs.items():
        Path(p).parent.mkdir(parents=True, exist_ok=True)
        Path(p).write_text(text, encoding="utf-8")
        print(f"wrote {Path(p).relative_to(ROOT)} ({len(text):,} chars)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
