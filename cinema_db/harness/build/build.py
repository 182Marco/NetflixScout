"""First offline build of the cinema database from the LOCAL sources only. No network, no OpenAI, no embeddings.

    python -m cinema_db.harness.build.build              # builds cinema_db/data/cinema.sqlite3 (refuses to overwrite)
    python -m cinema_db.harness.build.build --force      # replaces it; the previous file is kept as *.previous
    python -m cinema_db.harness.build.build --out FILE

Inputs (read-only, never modified): the Wikidata snapshots of the film and series projects, the film catalogue v3 and the series
catalogue s5. The build is deterministic: entities are processed in sorted order, ids are assigned in that order, and the result
carries a content digest (`build_info.content_sha256`) that a second build must reproduce exactly. The database is written to a
temporary file and renamed only after every check passed.

What is imported and what is not (and why) is in docs/cinema_db/BUILD_REPORT.md, generated by `verify`. In short: a fact is
imported only when the local sources state it AND name what it refers to; anything that would need a name or a code the local
sources do not hold (people with only a QID, award items, currency codes other than USD...) is left for the phase-4 targeted pass.
"""
