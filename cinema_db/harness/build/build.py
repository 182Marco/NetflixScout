USD = "Q4917"  # the only currency unit imported in phase 3 (see module docstring); its use is verified in the report
WORLDWIDE = "Q13780930"
FILM_KIND = {
    "short": "short", "tv_film": "tv_film", "tv_special": "tv_film", "tv_related": "other", "other": "other",
}
ROLE_TO_DB = {"director": "director", "writer": "writer", "cast": "cast", "composer": "composer", "cinematographer": "cinematographer",
              "editor": "editor", "producer": "producer", "production_designer": "production_designer", "costume_designer": "costume_designer",
              "creator": "creator"}
# Equivalent spellings used by the series catalogue for countries the film vocabulary names differently (same country, other wording).
COUNTRY_ALIASES = {"stati uniti d america": "stati uniti", "usa": "stati uniti", "gran bretagna": "regno unito"}
SAMPLE = 25  # examples kept per kind of problem in the report


def jsonl(path: Path) -> Iterator[dict]:
    with path.open(encoding="utf-8") as f:
        for line in f:
            if line.strip():
                yield json.loads(line)


class Inputs:
    def __init__(self, film_snapshot: Path = S.FILM_SNAPSHOT, series_snapshot: Path = S.SERIES_SNAPSHOT, film_catalog: Path = S.FILM_CATALOG, series_dir: Path = S.SERIES_DIR) -> None:
        self.film_snapshot, self.series_snapshot, self.film_catalog, self.series_dir = film_snapshot, series_snapshot, film_catalog, series_dir


class Builder:
    def __init__(self, conn: sqlite3.Connection, inputs: Inputs) -> None:
        self.c = conn
        self.inputs = inputs
        self.next_entity = 1
        self.report: dict[str, Any] = {"counts": collections.Counter(), "samples": collections.defaultdict(list), "skipped": collections.Counter()}
        self.src: dict[str, int] = {}
        self.genre_id: dict[str, int] = {}
        self.label_by_key: dict[str, int] = {}
        self.country_by_qid: dict[str, int] = {}
        self.country_by_norm: dict[str, int] = {}
        self.language_by_qid: dict[str, int] = {}
        self.person_by_qid: dict[str, int] = {}
        self.company_by_key: dict[str, int] = {}
        self.franchise_by_qid: dict[str, int] = {}
        self.work_by_qid: dict[str, int] = {}
        self.work_by_record: dict[str, int] = {}
        self.season_by_series_number: dict[tuple[int, int], int] = {}
        self.used_ids: dict[tuple[str, str], int] = {}
        self.labels: dict[str, dict[str, str]] = {}
        self.catalog_names: dict[str, str] = {}
        self.pending_relations: list[tuple[int, str, str, str]] = []
        self.batches: dict[str, list[tuple]] = collections.defaultdict(list)
        self.name_seen: set[tuple[int, str, str, str]] = set()
        self.credit_seen: set[tuple[int, int, str, str]] = set()
        self.assertion_seen: set[tuple] = set()

    # ---- small helpers ---------------------------------------------------------------------------------------------
    def note(self, kind: str, sample: Any = None, n: int = 1) -> None:
        self.report["skipped"][kind] += n
        if sample is not None and len(self.report["samples"][kind]) < SAMPLE:
            self.report["samples"][kind].append(sample)

    def count(self, key: str, n: int = 1) -> None:
        self.report["counts"][key] += n

    def entity(self, kind: str) -> int:
        eid = self.next_entity
        self.next_entity += 1
        self.batches["entity"].append((eid, kind))
        return eid

    # Natural key of each association table (the columns of its primary or unique key). The same assertion can arrive from two sources
    # (a work present in both catalogues); the first one is kept and the repeat is counted, never inserted twice.
    _NATURAL_KEY = {
        "work_genre": lambda r: (r[0], r[1]), "work_country": lambda r: (r[0], r[1], r[2]), "work_language": lambda r: (r[0], r[1], r[2]),
        "work_company": lambda r: (r[0], r[1], r[2]), "work_franchise": lambda r: (r[0], r[1]),
        "work_release": lambda r: (r[0], r[1] or 0, r[3], r[2]), "work_financial": lambda r: (r[0], r[1], r[2], r[3] or 0, r[6] or 0, r[5]),
    }

    def add(self, table: str, row: tuple) -> None:
        keyer = self._NATURAL_KEY.get(table)
        if keyer is not None:
            key = (table, keyer(row))
            if key in self.assertion_seen:
                self.count(f"assertion_repeated_from_another_source:{table}")
                return
            self.assertion_seen.add(key)
        self.batches[table].append(row)

    def flush(self) -> None:
        for table, rows in list(self.batches.items()):
            if not rows:
                continue
            if table == "entity_name":
                sql = ("INSERT INTO entity_name (entity_id, name, name_norm, language, kind, is_primary, source_id, source_ref) VALUES (?,?,?,?,?,?,?,?)")
            elif table == "external_id":
                sql = "INSERT INTO external_id (entity_id, scheme, value, is_primary, source_id, source_ref) VALUES (?,?,?,?,?,?)"
            elif table == "work":
                sql = ("INSERT INTO work (work_id, kind, parent_work_id, season_number, episode_number, release_date, release_year, end_date, end_year, runtime_min, status, source_id, source_ref) "
                       "VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?)")
            elif table == "person":
                sql = "INSERT INTO person (person_id, birth_date, birth_year, death_date, death_year, birth_country_id, source_id, source_ref) VALUES (?,?,?,?,?,?,?,?)"
            elif table == "company":
                sql = "INSERT INTO company (company_id, country_id, source_id, source_ref) VALUES (?,?,?,?)"
            elif table == "franchise":
                sql = "INSERT INTO franchise (franchise_id, source_id, source_ref) VALUES (?,?,?)"
            elif table == "credit":
                sql = "INSERT INTO credit (work_id, person_id, role, character_name, billing_order, credit_note, source_id, source_ref) VALUES (?,?,?,?,?,?,?,?)"
            elif table == "work_release":
                sql = "INSERT INTO work_release (work_id, country_id, release_date, kind, source_id, source_ref) VALUES (?,?,?,?,?,?)"
            elif table == "work_financial":
                sql = ("INSERT INTO work_financial (work_id, kind, scope, country_id, amount, currency, reference_year, source_id, source_ref) VALUES (?,?,?,?,?,?,?,?,?)")
            elif table == "entity":
                sql = "INSERT INTO entity VALUES (?,?)"
            else:
                sql = f"INSERT INTO {table} VALUES ({','.join('?' * len(rows[0]))})"
            if table == "entity":
                sql = "INSERT INTO entity VALUES (?,?)"
            self.c.executemany(sql, rows)
            rows.clear()

    def name_of(self, qid: str) -> tuple[str, str | None] | None:
        """(name, language) a Wikidata item can be shown with, from the snapshot labels first, then the catalogue."""
        lab = self.labels.get(qid, {})
        if lab.get("it"):
            return lab["it"], "it"
        if lab.get("en"):
            return lab["en"], "en"
        if qid in self.catalog_names:
            return self.catalog_names[qid], None
        return None

    def add_name(self, eid: int, name: str, kind: str, language: str | None, source: int, ref: str | None, primary: bool = False) -> bool:
        name = " ".join(str(name).split())
        norm = normalize_name(name)
        if not name or not norm:
            return False
        key = (eid, norm, language or "", kind)
        if key in self.name_seen:
            return False
        self.name_seen.add(key)
        self.add("entity_name", (eid, name, norm, language, kind, 1 if primary else 0, source, ref))
        return True

    def add_external(self, eid: int, scheme: str, value: str, source: int, ref: str | None, primary: bool = True) -> bool:
        value = str(value).strip()
        if not value:
            return False
        key = (scheme, value)
        owner = self.used_ids.get(key)
        if owner is not None:
            if owner != eid:
                self.note(f"id_conflict:{scheme}", {"scheme": scheme, "value": value, "kept_entity": owner, "dropped_entity": eid, "ref": ref})
            return False
        self.used_ids[key] = eid
        self.add("external_id", (eid, scheme, value, 1 if primary else 0, source, ref))
        return True

    # ---- phases -----------------------------------------------------------------------------------------------------
    def load_sources(self, film_snap: Snapshot, series_snap: Snapshot) -> None:
        specs = S.build_sources(film_snap.index_sha256, film_snap.acquired_range[1], series_snap.index_sha256, series_snap.acquired_range[1])
        for i, spec in enumerate(specs, 1):
            self.c.execute("INSERT INTO source VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?)", spec.row(i))
            self.src[spec.key] = i

    def load_genre_vocabulary(self) -> None:
        for i, g in enumerate(VOCABULARY, 1):
            self.genre_id[g.code] = i
        for g in VOCABULARY:
            parent = self.genre_id[g.parent] if g.parent else None
            self.c.execute("INSERT INTO genre VALUES (?,?,?,?,?,?,?)", (self.genre_id[g.code], g.code, g.label_en, g.label_it, parent, g.description, self.src["vocab"]))

    def genre_label(self, qid: str | None, label_it: str | None, label_en: str | None, source: int, ref: str | None) -> int | None:
        text = label_it or label_en
        if not text or not normalize_name(text):  # empty or only punctuation (found in the real series catalogue)
            self.note("genre_text_without_letters", text)
            return None
        key = f"wd:{qid}" if qid else f"txt:{normalize_name(text)}"
        if key in self.label_by_key:
            return self.label_by_key[key]
        label_id = len(self.label_by_key) + 1
        self.label_by_key[key] = label_id
        self.c.execute("INSERT INTO genre_label (label_id, wikidata_id, label_it, label_en, label_norm, source_id, source_ref) VALUES (?,?,?,?,?,?,?)",
                       (label_id, qid, label_it, label_en, normalize_name(text), source, ref))
        mapped = map_label(label_it, label_en)
        for code, kind, rule in mapped:
            self.c.execute("INSERT INTO genre_label_map VALUES (?,?,?,?,?)", (label_id, self.genre_id[code], kind, rule, self.src["vocab"]))
        self.count("genre_labels")
        self.count("genre_labels_mapped" if mapped else "genre_labels_unmapped")
        return label_id

    def country(self, qid: str) -> int | None:
        if qid in self.country_by_qid:
            return self.country_by_qid[qid]
        lab = self.labels.get(qid, {})
        if not (lab.get("it") or lab.get("en")):
            return None
        cid = len(self.country_by_qid) + 1
        self.country_by_qid[qid] = cid
        self.c.execute("INSERT INTO country (country_id, iso2, label_en, label_it, wikidata_id, source_id) VALUES (?,?,?,?,?,?)",
                       (cid, None, lab.get("en") or lab["it"], lab.get("it"), qid, self.src["wd_film"]))
        for t in (lab.get("it"), lab.get("en")):
            if t:
                self.country_by_norm.setdefault(normalize_name(t), cid)
        return cid

    def language(self, qid: str) -> int | None:
        if qid in self.language_by_qid:
            return self.language_by_qid[qid]
        lab = self.labels.get(qid, {})
        if not (lab.get("it") or lab.get("en")):
            return None
        lid = len(self.language_by_qid) + 1
        self.language_by_qid[qid] = lid
        self.c.execute("INSERT INTO language (language_id, iso639_1, iso639_3, label_en, label_it, wikidata_id, source_id) VALUES (?,?,?,?,?,?,?)",
                       (lid, None, None, lab.get("en") or lab["it"], lab.get("it"), qid, self.src["wd_film"]))
        return lid

    def person(self, qid: str, source: int) -> int | None:
        if qid in self.person_by_qid:
            return self.person_by_qid[qid]
        named = self.name_of(qid)
        if not named:
            return None
        eid = self.entity("person")
        self.person_by_qid[qid] = eid
        self.add("person", (eid, None, None, None, None, None, source, qid))
        name, lang = named
        self.add_name(eid, name, "primary", lang, source, qid, primary=True)
        lab = self.labels.get(qid, {})
        if lab.get("en") and lab.get("it") and normalize_name(lab["en"]) != normalize_name(lab["it"]):
            self.add_name(eid, lab["en"], "translated", "en", source, qid)
        self.add_external(eid, "wikidata", qid, source, qid)
        self.count("persons")
        return eid

    def company(self, key: str, name: str, lang: str | None, source: int, qid: str | None) -> int:
        if key in self.company_by_key:
            return self.company_by_key[key]
        eid = self.entity("company")
        self.company_by_key[key] = eid
        self.add("company", (eid, None, source, qid or key))
        self.add_name(eid, name, "primary", lang, source, qid or key, primary=True)
        if qid:
            self.add_external(eid, "wikidata", qid, source, qid)
        self.count("companies")
        return eid

    def franchise(self, qid: str, source: int) -> int | None:
        if qid in self.franchise_by_qid:
            return self.franchise_by_qid[qid]
        named = self.name_of(qid)
        if not named:
            return None
        eid = self.entity("franchise")
        self.franchise_by_qid[qid] = eid
        self.add("franchise", (eid, source, qid))
        self.add_name(eid, named[0], "primary", named[1], source, qid, primary=True)
        self.add_external(eid, "wikidata", qid, source, qid)
        self.count("franchises")
        return eid

    # ---- facts shared by films, series and TV films ---------------------------------------------------------------------
    def wikidata_facts(self, work_id: int, qid: str, s: dict[str, Any], source: int, *, catalog_characters: dict[str, str] | None = None, with_money: bool) -> None:
        ref = qid
        for qg in s["genres"]:
            lab = self.labels.get(qg, {})
            lid = self.genre_label(qg, lab.get("it"), lab.get("en"), source, qg)
            if lid:
                self.add("work_genre", (work_id, lid, source, qg))
                self.count("work_genre_assertions")
            else:
                self.note("genre_without_label", qg)
        for q in s["countries"]:
            cid = self.country(q)
            if cid:
                self.add("work_country", (work_id, cid, "origin", source, q))
            else:
                self.note("country_without_label", q)
        for q in s["languages"]:
            lid = self.language(q)
            if lid:
                self.add("work_language", (work_id, lid, "original", source, q))
            else:
                self.note("language_without_label", q)
        for role, rows in s["roles"].items():
            for row in rows:
                pid = self.person(row["person"], source)
                if pid is None:
                    self.note(f"credit_unnamed_person:{role}")
                    continue
                character = row.get("character") or (catalog_characters or {}).get(row["person"])
                key = (work_id, pid, ROLE_TO_DB[role], character or "")
                if key in self.credit_seen:
                    continue
                self.credit_seen.add(key)
                self.add("credit", (work_id, pid, ROLE_TO_DB[role], character, None, None, source, ref))
                self.count(f"credits:{role}")
        for kind, qs in s["companies"].items():
            role = {"production": "production", "distribution": "distribution", "network": "network"}[kind]
            for q in qs:
                named = self.name_of(q)
                if not named:
                    self.note("company_without_name", q)
                    continue
                cid = self.company(q, named[0], named[1], source, q)
                self.add("work_company", (work_id, cid, role, source, q))
        for kind, qs in s["franchises"].items():
            for q in qs:
                fid = self.franchise(q, source)
                if fid is None:
                    self.note("franchise_without_name", q)
                    continue
                self.add("work_franchise", (work_id, fid, None, "wikidata_series" if kind == "series" else "wikidata_franchise", source, q))
        for rel, targets in s["relations"].items():
            for t in targets:
                self.pending_relations.append((work_id, rel, t, qid))
        seen_release: set[tuple[int, str]] = set()
        for d in s["dates"]:
            for place in d["places"]:
                cid = self.country_by_qid.get(place)  # only places that are countries of some work; others are not guessed
                if cid and (cid, d["date"]) not in seen_release:
                    seen_release.add((cid, d["date"]))
                    self.add("work_release", (work_id, cid, d["date"], "unspecified", source, qid))
                elif not cid:
                    self.note("release_place_not_a_known_country", place)
        if with_money:
            seen_money: set[tuple] = set()
            for f in s["financial"]:
                if f["unit"] != USD:
                    self.note(f"money_unit_not_imported:{f['unit']}", n=1)
                    continue
                scope, country_id = "unspecified", None
                if f["places"]:
                    p = f["places"][0]
                    if p == WORLDWIDE:
                        scope = "worldwide"
                    else:
                        country_id = self.country_by_qid.get(p)
                        scope = "country" if country_id else "unspecified"
                year = year_ok(f["times"][0][:4]) if f["times"] else None
                key = (f["kind"], scope, country_id, year)
                if key in seen_money:
                    self.note("money_duplicate_same_key", {"qid": qid, "kind": f["kind"], "amount": f["amount"]})
                    continue
                seen_money.add(key)
                self.add("work_financial", (work_id, f["kind"], scope, country_id, f["amount"], "USD", year, source, qid))
                self.count(f"financial:{f['kind']}")
        if s["awards"]:
            self.count("award_statements_not_imported", len(s["awards"]))

    # ---- films -----------------------------------------------------------------------------------------------------------
    def films(self, catalog: list[dict], summaries: dict[str, dict]) -> None:
        wd, cat = self.src["wd_film"], self.src["cat_film"]
        for r in sorted(catalog, key=lambda r: r["film_id"]):
            qid = r.get("wikidata_id")
            s = summaries.get(qid) if qid else None
            fmt = r.get("work_format", "unknown")
            kind = FILM_KIND.get(fmt, "film")
            page_title = wikipedia_title(r.get("wikipedia_url"))
            twin = self.work_by_qid.get(qid) if qid else None
            if twin is None and page_title:
                twin = self.used_ids.get(("wikipedia_it", page_title))
            if twin is not None:
                self.merge_film_into(twin, r, s, wd, cat)
                continue
            wid = self.entity("work")
            if qid:
                self.work_by_qid[qid] = wid
            self.work_by_record[r["film_id"]] = wid
            year = year_ok(r.get("year"))
            earliest = min((d["date"] for d in s["dates"]), default=None) if s else None
            date = earliest if (earliest and year and int(earliest[:4]) == year) else None
            if earliest and year and int(earliest[:4]) != year:
                self.note("release_year_differs_catalog_vs_wikidata", {"film": r["film_id"], "catalog": year, "earliest_wikidata": earliest})
            runtime = r.get("duration_minutes") or (s["runtime_min"] if s else None)
            status = "unreleased" if fmt == "unreleased" else None
            self.add("work", (wid, kind, None, None, None, date, year, None, None, runtime, status, cat, f"{qid or r['film_id']};rev={r.get('source_revision_id')}"))
            self.count(f"works:{kind}")
            # names: primary Italian label (clean title) or the page title; translated, original, page title as aliases
            lab = s["labels"] if s else {}
            page_name = (page_title or r["title"]).replace("_", " ")
            primary = lab.get("it") or r["title"]
            ref = qid or r["film_id"]
            self.add_name(wid, primary, "primary", "it", wd if lab.get("it") else cat, ref, primary=True)
            if lab.get("en"):
                self.add_name(wid, lab["en"], "translated", "en", wd, ref)
            if r.get("original_title"):
                lang = next((t["language"] for t in (s["titles"] if s else []) if normalize_name(t["text"]) == normalize_name(r["original_title"])), None)
                self.add_name(wid, r["original_title"], "original", lang, cat, ref)
            self.add_name(wid, page_name, "alias", "it", cat, ref)
            # identifiers
            if qid:
                self.add_external(wid, "wikidata", qid, cat, ref)
            if r.get("imdb_id"):
                self.add_external(wid, "imdb_title", r["imdb_id"], cat, ref)
            if page_title:
                self.add_external(wid, "wikipedia_it", page_title, cat, f"{ref};page_id={r.get('wikipedia_page_id')}")
            if s:
                for scheme, values in s["ids"].items():
                    for i, v in enumerate(values):
                        # the catalogue's IMDb id stays the preferred one; a different one from Wikidata is kept as a second value
                        self.add_external(wid, scheme, v, wd, qid, primary=(i == 0 and not (scheme == "imdb_title" and r.get("imdb_id"))))
                characters = {a["wikidata_id"]: a["character"] for a in (r.get("actors") or []) if a.get("wikidata_id") and a.get("character")}
                self.wikidata_facts(wid, qid, s, wd, catalog_characters=characters, with_money=True)
            else:
                self.note("film_without_snapshot_entity", r["film_id"])
        self.flush()

    def merge_film_into(self, wid: int, r: dict, s: dict[str, Any] | None, wd: int, cat: int) -> None:
        """The film catalogue describes a work the series catalogue already created (same Wikidata item or same Wikipedia page):
        one work, not two. The series catalogue decides kind and primary name; the film catalogue only ADDS what it knows."""
        qid = r.get("wikidata_id")
        ref = qid or r["film_id"]
        self.work_by_record[r["film_id"]] = wid
        self.count("works_merged_film_into_series_catalog")
        if qid:
            self.work_by_qid.setdefault(qid, wid)
        lab = s["labels"] if s else {}
        page_title = wikipedia_title(r.get("wikipedia_url"))
        for name, kind, lang, src in ((lab.get("it"), "alias", "it", wd), (lab.get("en"), "translated", "en", wd), (r["title"], "alias", "it", cat),
                                      (r.get("original_title"), "original", None, cat), ((page_title or "").replace("_", " "), "alias", "it", cat)):
            if name:
                self.add_name(wid, name, kind, lang, src, ref)
        if qid:
            self.add_external(wid, "wikidata", qid, cat, ref)
        if r.get("imdb_id"):
            self.add_external(wid, "imdb_title", r["imdb_id"], cat, ref, primary=False)
        if r.get("duration_minutes"):
            self.c.execute("UPDATE work SET runtime_min = ? WHERE work_id = ? AND runtime_min IS NULL", (r["duration_minutes"], wid))
        if s:
            for scheme, values in s["ids"].items():
                for v in values:
                    self.add_external(wid, scheme, v, wd, qid, primary=False)
            self.wikidata_facts(wid, qid, s, wd, with_money=True)

    # ---- series, seasons, episodes, TV films --------------------------------------------------------------------------------
    def series(self, series_rows: list[dict], sents: dict[str, dict]) -> None:
        wd, cat = self.src["wd_series"], self.src["cat_series"]
        for r in sorted(series_rows, key=lambda r: r["record_id"]):
            if not r.get("default_search_eligible"):
                self.note(f"series_not_imported:{r.get('catalog_class')}", r["record_id"])
                continue
            ids = r.get("ids") or {}
            qid = ids.get("qid")
            reliable = bool(qid and r.get("ids_reliable"))
            s = sents.get(qid) if reliable else None
            kind = "miniseries" if r.get("subtype") == "miniseries" else "series"
            wid = self.entity("work")
            self.work_by_record[r["record_id"]] = wid
            if reliable:
                self.work_by_qid[qid] = wid
            year, end = year_ok(r.get("year")), year_ok(r.get("year_end"))
            self.add("work", (wid, kind, None, None, None, None, year, None, end, None, None, cat, f"{r['record_id']};rev={r.get('revision_id')}"))
            self.count(f"works:{kind}")
            ref = r["record_id"]
            lab = s["labels"] if s else {}
            page_title = wikipedia_title(r.get("wikipedia_url"))
            primary = lab.get("it") or r["title"]
            self.add_name(wid, primary, "primary", "it", wd if lab.get("it") else cat, ref, primary=True)
            if lab.get("en"):
                self.add_name(wid, lab["en"], "translated", "en", wd, ref)
            if r.get("original_title"):
                self.add_name(wid, r["original_title"], "original", None, cat, ref)
            self.add_name(wid, (page_title or r["title"]).replace("_", " "), "alias", "it", cat, ref)
            if page_title:
                self.add_external(wid, "wikipedia_it", page_title, cat, ref)
            if reliable:
                self.add_external(wid, "wikidata", qid, cat, ref)
                if ids.get("imdb_id"):
                    self.add_external(wid, "imdb_title", ids["imdb_id"], cat, ref)
                if ids.get("tmdb_id") and not (s and s["ids"].get("tmdb_tv")):
                    self.add_external(wid, "tmdb_tv", str(ids["tmdb_id"]), cat, ref)
                for scheme, values in (s["ids"] if s else {}).items():
                    for i, v in enumerate(values):
                        self.add_external(wid, scheme, v, wd, qid, primary=(i == 0 and not (scheme == "imdb_title" and ids.get("imdb_id"))))
            else:
                self.count("series_with_unreliable_ids")
            for text in r.get("genres") or []:
                lid = self.genre_label(None, text, None, cat, ref)
                if lid and (wid, lid) not in self._genre_pairs:
                    self._genre_pairs.add((wid, lid))
                    self.add("work_genre", (wid, lid, cat, ref))
            for text in ([r["country"]] if isinstance(r.get("country"), str) else (r.get("country") or [])):
                norm = normalize_name(text)
                cid = self.country_by_norm.get(norm) or self.country_by_norm.get(COUNTRY_ALIASES.get(norm, ""))
                if cid and not (s and s["countries"]):
                    self.add("work_country", (wid, cid, "origin", cat, ref))
                elif not cid:
                    self.note("series_country_text_not_a_known_country", text)
            if r.get("network"):
                nets = r["network"] if isinstance(r["network"], list) else [r["network"]]
                for n in nets:
                    if isinstance(n, str) and normalize_name(n):
                        cid = self.company(f"net:{normalize_name(n)}", n, None, cat, None)
                        self.add("work_company", (wid, cid, "network", cat, ref))
            if s:
                self.wikidata_facts(wid, qid, s, wd, with_money=False)
        self.flush()

    def seasons_and_episodes(self, seasons: list[dict], episodes: list[dict], meta: Iterable[dict]) -> None:
        cat = self.src["cat_series"]
        for r in sorted(seasons, key=lambda r: r["record_id"]):
            parent = self.work_by_record.get(r.get("series_id"))
            if parent is None:
                self.note("season_without_imported_series", r["record_id"])
                continue
            wid = self.entity("work")
            self.work_by_record[r["record_id"]] = wid
            number = r.get("season_number")
            if isinstance(number, int) and number >= 0:
                self.season_by_series_number[(parent, number)] = wid
            else:
                number = None
            self.add("work", (wid, "season", parent, number, None, None, None, None, None, None, None, cat, r["record_id"]))
            self.count("works:season")
            self.add_name(wid, r["title"], "primary", "it", cat, r["record_id"], primary=True)
            page = wikipedia_title(r.get("wikipedia_url"))
            if page:
                self.add_external(wid, "wikipedia_it", page, cat, r["record_id"])
        self.flush()
        numbered: set[tuple[int, int | None, int]] = set()
        for r in sorted(episodes, key=lambda r: r["record_id"]):
            wid = self._episode(r, cat)
            if wid is not None and isinstance(r.get("episode_number"), int):
                parent = self.work_by_record.get(r.get("series_id"))
                numbered.add((parent or 0, r.get("season_number"), r["episode_number"]))
        self.flush()
        for r in sorted(meta, key=lambda r: r["record_id"]):
            parent = self.work_by_record.get(r.get("series_id"))
            if parent is not None and isinstance(r.get("episode_number"), int) and (parent, r.get("season_number"), r["episode_number"]) in numbered:
                self.note("episode_row_duplicates_an_episode_page")
                continue
            self._episode(r, cat)
        self.flush()

    def _episode(self, r: dict, cat: int) -> int | None:
        series = self.work_by_record.get(r.get("series_id"))
        if series is None:
            self.note("episode_without_imported_series", r["record_id"])
            return None
        number = r.get("season_number") if isinstance(r.get("season_number"), int) and r["season_number"] >= 0 else None
        parent = self.work_by_record.get(r.get("season_id")) or (self.season_by_series_number.get((series, number)) if number is not None else None) or series
        title = r.get("title_it") or r.get("title")
        if not title or not normalize_name(title):
            self.note("episode_without_title", r["record_id"])
            return None
        wid = self.entity("work")
        self.work_by_record[r["record_id"]] = wid
        date = next((d for d in (italian_date(t) for t in (r.get("air_dates") or [])) if d), None)
        if r.get("air_dates") and not date:
            self.note("episode_air_date_not_parsed", (r.get("air_dates") or [None])[0])
        ep_no = r.get("episode_number") if isinstance(r.get("episode_number"), int) and r["episode_number"] >= 0 else None
        self.add("work", (wid, "episode", parent, number, ep_no, date, year_ok(date[:4]) if date else None, None, None, None, None, cat, r["record_id"]))
        self.count("works:episode")
        self.add_name(wid, title, "primary", "it", cat, r["record_id"], primary=True)
        if r.get("title_original"):
            self.add_name(wid, r["title_original"], "original", None, cat, r["record_id"])
        page = wikipedia_title(r.get("wikipedia_url"))
        if page:
            self.add_external(wid, "wikipedia_it", page, cat, r["record_id"])
        ids = r.get("ids") or {}
        if ids.get("qid"):
            self.add_external(wid, "wikidata", ids["qid"], cat, r["record_id"])
        if ids.get("imdb_id"):
            self.add_external(wid, "imdb_title", ids["imdb_id"], cat, r["record_id"])
        return wid

    def tv_movies(self, rows: list[dict], sents: dict[str, dict]) -> None:
        wd, cat = self.src["wd_series"], self.src["cat_series"]
        for r in sorted(rows, key=lambda r: r["record_id"]):
            ids = r.get("ids") or {}
            qid = ids.get("qid")
            reliable = bool(qid and r.get("ids_reliable"))
            s = sents.get(qid) if reliable else None
            wid = self.entity("work")
            self.work_by_record[r["record_id"]] = wid
            if reliable:
                self.work_by_qid[qid] = wid
            self.add("work", (wid, "tv_film", None, None, None, None, year_ok(r.get("year")), None, None, None, None, cat, f"{r['record_id']};rev={r.get('revision_id')}"))
            self.count("works:tv_film")
            ref = r["record_id"]
            lab = s["labels"] if s else {}
            self.add_name(wid, lab.get("it") or r["title"], "primary", "it", wd if lab.get("it") else cat, ref, primary=True)
            if lab.get("en"):
                self.add_name(wid, lab["en"], "translated", "en", wd, ref)
            if r.get("original_title"):
                self.add_name(wid, r["original_title"], "original", None, cat, ref)
            page = wikipedia_title(r.get("wikipedia_url"))
            if page:
                self.add_name(wid, page.replace("_", " "), "alias", "it", cat, ref)
                self.add_external(wid, "wikipedia_it", page, cat, ref)
            if reliable:
                self.add_external(wid, "wikidata", qid, cat, ref)
                if ids.get("imdb_id"):
                    self.add_external(wid, "imdb_title", ids["imdb_id"], cat, ref)
                if ids.get("tmdb_id"):
                    self.add_external(wid, "tmdb_movie", str(ids["tmdb_id"]), cat, ref)
            for text in r.get("genres") or []:
                lid = self.genre_label(None, text, None, cat, ref)
                if lid and (wid, lid) not in self._genre_pairs:
                    self._genre_pairs.add((wid, lid))
                    self.add("work_genre", (wid, lid, cat, ref))
            if s:
                self.wikidata_facts(wid, qid, s, wd, with_money=False)
        self.flush()

    def relations(self) -> None:
        wd = self.src["wd_film"]
        seen: set[tuple[int, int, str]] = set()
        for work_id, rel, target, qid in self.pending_relations:
            tid = self.work_by_qid.get(target)
            if tid is None:
                named = self.name_of(target)
                if not named:
                    self.note(f"relation_target_without_label:{rel}", target)
                    continue
                tid = self.entity("work")
                self.work_by_qid[target] = tid
                self.add("work", (tid, "other", None, None, None, None, None, None, None, None, None, wd, target))
                self.add_name(tid, named[0], "primary", named[1], wd, target, primary=True)
                self.add_external(tid, "wikidata", target, wd, target)
                self.count("works:other_relation_target")
            if rel == "based_on":
                row = (work_id, tid, "based_on")
            elif rel == "follows":
                row = (work_id, tid, "follows")
            elif rel == "followed_by":
                row = (tid, work_id, "follows")
            elif rel == "derivative":
                row = (tid, work_id, "based_on")  # X has derivative Y  =>  Y is based on X
            else:
                continue
            if row[0] == row[1] or row in seen:
                continue
            seen.add(row)
            self.add("work_relation", (row[0], row[1], row[2], wd, qid))
            self.count(f"relations:{row[2]}")
        self.flush()

    _genre_pairs: set[tuple[int, int]]

    def finish(self) -> None:
        self.flush()


def invariants(conn: sqlite3.Connection) -> list[str]:
    """Rules the schema cannot state: every entity has exactly one primary name; seasons and episodes have a parent."""
    out = []
    for table, key in (("work", "work_id"), ("person", "person_id"), ("company", "company_id"), ("franchise", "franchise_id")):
        bad = conn.execute(f"SELECT count(*) FROM {table} t WHERE (SELECT count(*) FROM entity_name n WHERE n.entity_id = t.{key} AND n.is_primary = 1) <> 1").fetchone()[0]
        if bad:
            out.append(f"{bad} {table} rows without exactly one primary name")
    return out


def content_digest(conn: sqlite3.Connection) -> str:
    """SHA-256 over every row of every data table in rowid order (build_info and the FTS shadow tables excluded)."""
    h = hashlib.sha256()
    tables = [r[0] for r in conn.execute("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' AND name NOT LIKE 'entity_name_fts%' AND name <> 'build_info' ORDER BY name")]
    for t in tables:
        h.update(f"#{t}\n".encode())
        for row in conn.execute(f'SELECT * FROM "{t}" ORDER BY rowid'):
            h.update(json.dumps(row, ensure_ascii=False, separators=(",", ":")).encode())
            h.update(b"\n")
    return h.hexdigest()


def run_build(out: Path, inputs: Inputs | None = None, *, force: bool = False, log=print) -> dict[str, Any]:
    inputs = inputs or Inputs()
    out = Path(out)
    if out.exists() and not force:
        raise FileExistsError(f"{out} exists; use --force to replace it (the old file is kept as {out.name}.previous).")
    tmp = out.with_name(out.name + ".building")
    if tmp.exists():
        tmp.unlink()
    t0 = time.time()
    create_database(tmp)
    conn = sqlite3.connect(tmp)
    conn.execute("PRAGMA foreign_keys = OFF")  # bulk load; foreign_key_check below is the guard
    conn.execute("PRAGMA journal_mode = OFF")
    conn.execute("PRAGMA synchronous = OFF")
    b = Builder(conn, inputs)
    b._genre_pairs = set()
    try:
        log("reading snapshots …")
        film_snap, series_snap = Snapshot(inputs.film_snapshot), Snapshot(inputs.series_snapshot)
        b.load_sources(film_snap, series_snap)
        b.load_genre_vocabulary()
        catalog = list(jsonl(inputs.film_catalog))
        series_rows = list(jsonl(inputs.series_dir / "series.jsonl"))
        tv_rows = list(jsonl(inputs.series_dir / "tv_movies.jsonl"))
        b.labels = {**series_snap.labels(), **film_snap.labels()}
        for r in catalog:
            for p in (r.get("director") or []) + (r.get("actors") or []):
                if p.get("wikidata_id") and p.get("name"):
                    b.catalog_names.setdefault(p["wikidata_id"], p["name"])
        film_summaries = {q: X.summarize(q, e) for q, e in film_snap.entities()}
        needed = {(r.get("ids") or {}).get("qid") for r in series_rows + tv_rows if r.get("ids_reliable")} - {None}
        series_summaries = {q: X.summarize(q, e) for q, e in series_snap.entities() if q in needed}
        log(f"films: {len(catalog)}, snapshot entities: {len(film_summaries)}; series: {len(series_rows)}, tv movies: {len(tv_rows)}")
        # countries and languages first, from every QID the imported works use, so releases and series text can resolve them
        for s in sorted(film_summaries.values(), key=lambda s: s["qid"]):
            for q in s["countries"]:
                b.country(q)
            for q in s["languages"]:
                b.language(q)
        log("series, seasons, episodes, tv films (the series catalogue decides television works) …")
        b.series(series_rows, series_summaries)
        b.seasons_and_episodes(list(jsonl(inputs.series_dir / "seasons.jsonl")), list(jsonl(inputs.series_dir / "episodes.jsonl")), jsonl(inputs.series_dir / "episodes_meta.jsonl"))
        b.tv_movies(tv_rows, series_summaries)
        log("films …")
        b.films(catalog, film_summaries)
        log("relations …")
        b.relations()
        b.finish()
        log("fts index, checks …")
        rebuild_fts(conn)
        conn.execute("ANALYZE")
        conn.commit()
        conn.execute("PRAGMA foreign_keys = ON")
        fk = conn.execute("PRAGMA foreign_key_check").fetchall()
        integrity = conn.execute("PRAGMA integrity_check").fetchone()[0]
        problems = check_fts(conn) + invariants(conn)
        if fk or integrity != "ok" or problems:
            raise RuntimeError(f"build failed its own checks: foreign keys {fk[:5]}, integrity {integrity}, fts {problems}")
        digest = content_digest(conn)
        info = {
            "schema_version": str(SCHEMA_VERSION), "content_sha256": digest, "film_snapshot_index_sha256": film_snap.index_sha256,
            "series_snapshot_index_sha256": series_snap.index_sha256, "film_catalog_sha256": S.sha256_file(inputs.film_catalog),
            "builder": "cinema_db.harness.build.build/1",
        }
        for k, v in info.items():
            conn.execute("INSERT OR REPLACE INTO build_info VALUES (?,?)", (k, v))
        conn.commit()
        conn.execute("VACUUM")
        conn.close()
    except BaseException:
        conn.close()
        raise
    out.parent.mkdir(parents=True, exist_ok=True)
    if out.exists():
        os.replace(out, out.with_name(out.name + ".previous"))
    os.replace(tmp, out)
    report = {"counts": dict(b.report["counts"]), "skipped": dict(b.report["skipped"]), "samples": dict(b.report["samples"]), "content_sha256": digest,
              "seconds": round(time.time() - t0, 1), "bytes": out.stat().st_size, "inputs": info}
    (out.with_name(out.stem + ".build_report.json")).write_text(json.dumps(report, indent=2, ensure_ascii=False, sort_keys=True) + "\n", encoding="utf-8")
    log(f"built {out} ({report['bytes'] / 1e6:.0f} MB) in {report['seconds']} s; content_sha256 {digest[:16]}…")
    return report


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", type=Path, default=S.DEFAULT_DB)
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args(argv)
    run_build(args.out, force=args.force)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
