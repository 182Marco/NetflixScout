    def films(self, catalog: list[dict], summaries: dict[str, dict]) -> None:
        wd, cat = self.src["wd_film"], self.src["cat_film"]
        for r in sorted(catalog, key=lambda r: r["film_id"]):
            qid = r.get("wikidata_id")
            s = summaries.get(qid) if qid else None
            fmt = r.get("work_format", "unknown")
            kind = FILM_KIND.get(fmt, "film")
            page_title = wikipedia_title(r.get("wikipedia_url"))
            twin = self.work_by_qid.get(qid) if qid else None
            if twin is None and page_title:
                twin = self.used_ids.get(("wikipedia_it", page_title))
            if twin is not None:
                self.merge_film_into(twin, r, s, wd, cat)
                continue
            wid = self.entity("work")
            if qid:
                self.work_by_qid[qid] = wid
            self.work_by_record[r["film_id"]] = wid
            year = year_ok(r.get("year"))
            earliest = min((d["date"] for d in s["dates"]), default=None) if s else None
            date = earliest if (earliest and year and int(earliest[:4]) == year) else None
            if earliest and year and int(earliest[:4]) != year:
                self.note("release_year_differs_catalog_vs_wikidata", {"film": r["film_id"], "catalog": year, "earliest_wikidata": earliest})
            runtime = r.get("duration_minutes") or (s["runtime_min"] if s else None)
            status = "unreleased" if fmt == "unreleased" else None
            self.add("work", (wid, kind, None, None, None, date, year, None, None, runtime, status, cat, f"{qid or r['film_id']};rev={r.get('source_revision_id')}"))
            self.count(f"works:{kind}")
            # names: primary Italian label (clean title) or the page title; translated, original, page title as aliases
            lab = s["labels"] if s else {}
            page_name = (page_title or r["title"]).replace("_", " ")
            primary = lab.get("it") or r["title"]
            ref = qid or r["film_id"]
            self.add_name(wid, primary, "primary", "it", wd if lab.get("it") else cat, ref, primary=True)
            if lab.get("en"):
                self.add_name(wid, lab["en"], "translated", "en", wd, ref)
            if r.get("original_title"):
                lang = next((t["language"] for t in (s["titles"] if s else []) if normalize_name(t["text"]) == normalize_name(r["original_title"])), None)
                self.add_name(wid, r["original_title"], "original", lang, cat, ref)
            self.add_name(wid, page_name, "alias", "it", cat, ref)
            # identifiers
            if qid:
                self.add_external(wid, "wikidata", qid, cat, ref)
            if r.get("imdb_id"):
                self.add_external(wid, "imdb_title", r["imdb_id"], cat, ref)
            if page_title:
                self.add_external(wid, "wikipedia_it", page_title, cat, f"{ref};page_id={r.get('wikipedia_page_id')}")
            if s:
                for scheme, values in s["ids"].items():
                    for i, v in enumerate(values):
                        # the catalogue's IMDb id stays the preferred one; a different one from Wikidata is kept as a second value
                        self.add_external(wid, scheme, v, wd, qid, primary=(i == 0 and not (scheme == "imdb_title" and r.get("imdb_id"))))
                characters = {a["wikidata_id"]: a["character"] for a in (r.get("actors") or []) if a.get("wikidata_id") and a.get("character")}
                self.wikidata_facts(wid, qid, s, wd, catalog_characters=characters, with_money=True)
            else:
                self.note("film_without_snapshot_entity", r["film_id"])
        self.flush()

    def merge_film_into(self, wid: int, r: dict, s: dict[str, Any] | None, wd: int, cat: int) -> None:
        """The film catalogue describes a work the series catalogue already created (same Wikidata item or same Wikipedia page):
        one work, not two. The series catalogue decides kind and primary name; the film catalogue only ADDS what it knows."""
        qid = r.get("wikidata_id")
        ref = qid or r["film_id"]
        self.work_by_record[r["film_id"]] = wid
        self.count("works_merged_film_into_series_catalog")
        if qid:
            self.work_by_qid.setdefault(qid, wid)
        lab = s["labels"] if s else {}
        page_title = wikipedia_title(r.get("wikipedia_url"))
        for name, kind, lang, src in ((lab.get("it"), "alias", "it", wd), (lab.get("en"), "translated", "en", wd), (r["title"], "alias", "it", cat),
                                      (r.get("original_title"), "original", None, cat), ((page_title or "").replace("_", " "), "alias", "it", cat)):
            if name:
                self.add_name(wid, name, kind, lang, src, ref)
        if qid:
            self.add_external(wid, "wikidata", qid, cat, ref)
        if r.get("imdb_id"):
            self.add_external(wid, "imdb_title", r["imdb_id"], cat, ref, primary=False)
        if r.get("duration_minutes"):
            self.c.execute("UPDATE work SET runtime_min = ? WHERE work_id = ? AND runtime_min IS NULL", (r["duration_minutes"], wid))
        if s:
            for scheme, values in s["ids"].items():
                for v in values:
                    self.add_external(wid, scheme, v, wd, qid, primary=False)
            self.wikidata_facts(wid, qid, s, wd, with_money=True)

